class Komputer
{
    public string Motherboard;
    public string CPU;
    public string GPU;
    public string RAM;
    public double Harga;

    public Komputer(string motherboard, string cpu, string gpu, string ram, double harga)
    {
        Motherboard = motherboard;
        CPU = cpu;
        GPU = gpu;
        RAM = ram;
        Harga = harga;
    }
}

